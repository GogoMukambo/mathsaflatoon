window.getTopicImageData = function(yearId, unitId, topicId) {
  const images = window.MODULE_IMAGES || {};
  if (yearId && topicId && images[`${yearId}:${topicId}`]) {
    return images[`${yearId}:${topicId}`];
  }
  if (yearId && unitId && images[`${yearId}:${unitId}`]) {
    return images[`${yearId}:${unitId}`];
  }
  if (unitId && images[`9:${unitId}`]) {
    return images[`9:${unitId}`];
  }
  return images["cover"];
};
