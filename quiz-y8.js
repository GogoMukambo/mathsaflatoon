(function tagScienceQuizUnits() {
  const bank = window.QUIZ_BANK || {};
  Object.keys(bank).forEach((key) => {
    (bank[key] || []).forEach((q) => {
      const s = q.source || "";
      if (/Unit 1 & 4\.1/i.test(s)) q.unitIds = ["1", "4"];
      else if (/photosynthesis|carbon cycle/i.test(s)) q.unitIds = ["1"];
      else if (/maintaining life|4\.2|4\.3/i.test(s)) q.unitIds = ["4"];
      else if (/atom|groups 1|bonding|giant structures/i.test(s)) q.unitIds = ["2"];
      else if (/rates of reaction/i.test(s)) q.unitIds = ["8"];
      else if (/density|energy|unit 3/i.test(s)) q.unitIds = ["3"];
      else if (/sound and space/i.test(s)) q.unitIds = ["6"];
    });
  });
})();
